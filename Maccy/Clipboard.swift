import AppKit
import Defaults
import KeyboardShortcuts
import Sauce

class Clipboard {
  static let shared = Clipboard()

  typealias OnNewCopyHook = (HistoryItem) -> Void

  private var onNewCopyHooks: [OnNewCopyHook] = []
  var changeCount: Int
  private var lastPlainTextPasteAt: Date = .distantPast
  private var isPerformingPlainTextPaste: Bool = false

  private let pasteboard = NSPasteboard.general

  private var timer: Timer?

  private let dynamicTypePrefix = "dyn."
  private let microsoftSourcePrefix = "com.microsoft.ole.source."
  private let supportedTypes: Set<NSPasteboard.PasteboardType> = [
    .fileURL,
    .html,
    .png,
    .rtf,
    .string,
    .tiff
  ]
  private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
    .autoGenerated,
    .concealed,
    .transient
  ]
  private let unpersistableTypes: Set<NSPasteboard.PasteboardType> = [
    .appleWebArchive,
    .safariWebArchve
  ]

  // When plain text (.string) is already present, cap redundant HTML/RTF styling blobs at 5 MB
  // so copying large logs/code from IDEs or browsers doesn't dump 50+ MB of HTML into SQLite.
  private let maxRedundantRichTextBytes = 5 * 1_048_576

  private var enabledTypes: Set<NSPasteboard.PasteboardType> { Defaults[.enabledPasteboardTypes] }
  private var disabledTypes: Set<NSPasteboard.PasteboardType> { supportedTypes.subtracting(enabledTypes) }

  private var sourceApp: NSRunningApplication? { NSWorkspace.shared.frontmostApplication }

  init() {
    changeCount = pasteboard.changeCount
  }

  func onNewCopy(_ hook: @escaping OnNewCopyHook) {
    onNewCopyHooks.append(hook)
  }

  func clearHooks() {
    onNewCopyHooks = []
  }

  func start() {
    timer = Timer.scheduledTimer(
      timeInterval: Defaults[.clipboardCheckInterval],
      target: self,
      selector: #selector(checkForChangesInPasteboard),
      userInfo: nil,
      repeats: true
    )
  }

  func restart() {
    timer?.invalidate()
    start()
  }

  func isPersistable(_ type: NSPasteboard.PasteboardType) -> Bool {
    return !unpersistableTypes.contains(type) &&
             !type.rawValue.hasPrefix(microsoftSourcePrefix) &&
             !type.rawValue.hasPrefix(dynamicTypePrefix)
  }

  @MainActor
  func copyInMaccy(_ string: String) {
    pasteboard.clearContents()
    pasteboard.setString(string, forType: .string)
    pasteboard.setString(NSPasteboard.PasteboardType.fromMaccy.rawValue, forType: .source)
    sync()
    checkForChangesInPasteboard()
  }

  @MainActor
  func copy(_ item: HistoryItem?, removeFormatting: Bool = false) {
    guard let item else { return }

    pasteboard.clearContents()
    var contents = item.contents

    if removeFormatting {
      contents = clearFormatting(contents)
    }

    for content in contents {
      guard content.type != NSPasteboard.PasteboardType.fileURL.rawValue else { continue }
      pasteboard.setData(content.value, forType: NSPasteboard.PasteboardType(content.type))
    }

    let fileURLItems: [NSPasteboardItem] = contents.compactMap { item in
      guard item.type == NSPasteboard.PasteboardType.fileURL.rawValue else { return nil }
      guard let value = item.value else { return nil }
      let pasteItem = NSPasteboardItem()
      pasteItem.setData(value, forType: NSPasteboard.PasteboardType(item.type))
      return pasteItem
    }
    pasteboard.writeObjects(fileURLItems)

    pasteboard.setString("", forType: .fromMaccy)
    pasteboard.setString(item.application ?? "", forType: .source)
    sync()

    Task {
      Notifier.notify(body: item.title, sound: .knock)
      checkForChangesInPasteboard()
    }
  }

  @MainActor
  func pasteLatestPlainText() {
    let now = Date.now
    guard now.timeIntervalSince(lastPlainTextPasteAt) > 0.25 else {
      return
    }
    lastPlainTextPasteAt = now

    // Capture any copy made within the last few milliseconds before the timer tick
    checkForChangesInPasteboard()

    let wasPopupOpen = !AppState.shared.popup.isClosed()
    if wasPopupOpen {
      AppState.shared.popup.close()
    }

    let latestItem = History.shared.mostRecentItem
    guard let plainTextData = extractPlainTextData(from: latestItem), !plainTextData.isEmpty else {
      return
    }

    let initialChangeCount = pasteboard.changeCount
    let sourceBundle = latestItem?.application

    // Temporarily disable .popup (⌘⇧V) so synthetic ⌘V while user holds Shift never triggers popup
    KeyboardShortcuts.disable(.popup)
    let pasteDelay: TimeInterval = 0.06
    DispatchQueue.main.asyncAfter(deadline: .now() + pasteDelay) {
      // If another hotkey utility (e.g. an Alfred workflow also bound to ⌘⇧C) already rewrote
      // the pasteboard and triggered auto-paste during this window, avoid pasting a second time.
      if self.pasteboard.changeCount != initialChangeCount {
        self.changeCount = self.pasteboard.changeCount
        if AppState.shared.popup.isClosed() {
          KeyboardShortcuts.enable(.popup)
        }
        return
      }

      self.isPerformingPlainTextPaste = true

      let allowedPlainOnlyTypes: Set<NSPasteboard.PasteboardType> = [
        .string,
        NSPasteboard.PasteboardType("NSStringPboardType"),
        .transient,
        .autoGenerated,
        .fromMaccy,
        .source
      ]
      let currentTypes = Set(self.pasteboard.types ?? [])
      let alreadyCleanPlainText = !currentTypes.isEmpty
        && currentTypes.isSubset(of: allowedPlainOnlyTypes)
        && self.pasteboard.data(forType: .string) == plainTextData

      if !alreadyCleanPlainText {
        self.pasteboard.clearContents()
        self.pasteboard.setData(plainTextData, forType: .string)
        // Tag as transient & auto-generated (nspasteboard.org) so external clipboard managers
        // (such as Alfred Fast Append / Clipboard Merging) never merge or duplicate this write.
        self.pasteboard.setData(Data(), forType: .transient)
        self.pasteboard.setData(Data(), forType: .autoGenerated)
        self.pasteboard.setString("", forType: .fromMaccy)
        if let app = sourceBundle {
          self.pasteboard.setString(app, forType: .source)
        }
        self.changeCount = self.pasteboard.changeCount
        self.sync()
      }

      self.postCleanCommandVPaste()

      DispatchQueue.main.asyncAfter(deadline: .now() + 0.2) {
        self.changeCount = self.pasteboard.changeCount
        self.isPerformingPlainTextPaste = false
        if AppState.shared.popup.isClosed() {
          KeyboardShortcuts.enable(.popup)
        }
      }
    }
  }

  private func postCleanCommandVPaste(syntheticTag: Int64 = 0) {
    Accessibility.check()

    let cmdFlag = CGEventFlags(rawValue: UInt64(KeyChord.pasteKeyModifiers.rawValue) | 0x000008)
    var vCode = Sauce.shared.keyCode(for: KeyChord.pasteKey)

    if KeyboardLayout.current.commandSwitchesToQWERTY && cmdFlag.contains(.maskCommand) {
      vCode = KeyChord.pasteKey.QWERTYKeyCode
    }

    // Use .privateState so physical Shift key from ⌘⇧C does not leak into the synthetic ⌘V event
    let source = CGEventSource(stateID: .privateState)
    source?.setLocalEventsFilterDuringSuppressionState(
      [.permitLocalMouseEvents, .permitSystemDefinedEvents],
      state: .eventSuppressionStateSuppressionInterval
    )

    let keyVDown = CGEvent(keyboardEventSource: source, virtualKey: vCode, keyDown: true)
    let keyVUp = CGEvent(keyboardEventSource: source, virtualKey: vCode, keyDown: false)
    keyVDown?.flags = cmdFlag
    keyVUp?.flags = cmdFlag
    if syntheticTag != 0 {
      keyVDown?.setIntegerValueField(.eventSourceUserData, value: syntheticTag)
      keyVUp?.setIntegerValueField(.eventSourceUserData, value: syntheticTag)
    }
    keyVDown?.post(tap: .cgSessionEventTap)
    keyVUp?.post(tap: .cgSessionEventTap)
  }

  func isAppIgnored(_ bundleIdentifier: String?) -> Bool {
    guard let bundleIdentifier, !bundleIdentifier.isEmpty else { return false }
    return shouldIgnore(bundleIdentifier)
  }

  @MainActor
  func deleteCharactersBeforeCursor(
    count: Int,
    syntheticTag: Int64,
    useDirectResponderForMaccy: Bool = false
  ) {
    guard count > 0 else { return }

    if useDirectResponderForMaccy,
       let textView = NSApp.keyWindow?.firstResponder as? NSTextView {
      for _ in 0..<count {
        textView.deleteBackward(nil)
      }
      return
    }

    Accessibility.check()

    let source = CGEventSource(stateID: .privateState)
    source?.setLocalEventsFilterDuringSuppressionState(
      [.permitLocalMouseEvents, .permitSystemDefinedEvents],
      state: .eventSuppressionStateSuppressionInterval
    )

    let backspaceKeyCode: CGKeyCode = 51
    for _ in 0..<count {
      let down = CGEvent(keyboardEventSource: source, virtualKey: backspaceKeyCode, keyDown: true)
      let up = CGEvent(keyboardEventSource: source, virtualKey: backspaceKeyCode, keyDown: false)
      down?.flags = []
      up?.flags = []
      down?.setIntegerValueField(.eventSourceUserData, value: syntheticTag)
      up?.setIntegerValueField(.eventSourceUserData, value: syntheticTag)
      down?.post(tap: .cgSessionEventTap)
      up?.post(tap: .cgSessionEventTap)
    }
  }

  @MainActor
  func performExpansionSteps(
    _ steps: [ExpandedActionStep],
    targetApp: NSRunningApplication? = nil,
    restoreClipboard: Bool = Defaults[.restoreClipboardAfterExpansion],
    syntheticTag: Int64 = 0x4D43_5953,
    useDirectResponderForMaccy: Bool = false
  ) async {
    guard !steps.isEmpty else { return }

    let savedPasteboardSnapshot: [[(NSPasteboard.PasteboardType, Data)]] = restoreClipboard
      ? snapshotCurrentPasteboard()
      : []

    isPerformingPlainTextPaste = true
    KeyboardShortcuts.disable(.popup)

    if let targetApp, !targetApp.isActive {
      targetApp.activate()
      try? await Task.sleep(for: .milliseconds(80))
    }

    for step in steps {
      switch step {
      case .pasteText(let text, let htmlData, let rtfData):
        pasteboard.clearContents()
        if let rtfData, !rtfData.isEmpty {
          pasteboard.setData(rtfData, forType: .rtf)
        }
        if let htmlData, !htmlData.isEmpty {
          pasteboard.setData(htmlData, forType: .html)
        }
        pasteboard.setString(text, forType: .string)
        pasteboard.setData(Data(), forType: .transient)
        pasteboard.setData(Data(), forType: .autoGenerated)
        pasteboard.setString("", forType: .fromMaccy)
        changeCount = pasteboard.changeCount
        sync()
        if useDirectResponderForMaccy && NSApp.sendAction(#selector(NSText.paste(_:)), to: nil, from: nil) {
          try? await Task.sleep(for: .milliseconds(25))
        } else {
          postCleanCommandVPaste(syntheticTag: syntheticTag)
          try? await Task.sleep(for: .milliseconds(65))
        }

      case .pasteImage(let pngData):
        pasteboard.clearContents()
        pasteboard.setData(pngData, forType: .png)
        pasteboard.setData(Data(), forType: .transient)
        pasteboard.setData(Data(), forType: .autoGenerated)
        pasteboard.setString("", forType: .fromMaccy)
        changeCount = pasteboard.changeCount
        sync()
        if useDirectResponderForMaccy && NSApp.sendAction(#selector(NSText.paste(_:)), to: nil, from: nil) {
          try? await Task.sleep(for: .milliseconds(35))
        } else {
          postCleanCommandVPaste(syntheticTag: syntheticTag)
          try? await Task.sleep(for: .milliseconds(85))
        }

      case .keyPress(let kind, let count):
        guard count > 0 else { continue }
        postEmulatedKeys(kind: kind, count: min(count, 500), syntheticTag: syntheticTag)
        try? await Task.sleep(for: .milliseconds(25))

      case .delayMilliseconds(let ms):
        try? await Task.sleep(for: .milliseconds(ms))
      }
    }

    try? await Task.sleep(for: .milliseconds(180))

    if restoreClipboard {
      restorePasteboard(from: savedPasteboardSnapshot)
    }

    changeCount = pasteboard.changeCount
    isPerformingPlainTextPaste = false
    if AppState.shared.popup.isClosed() {
      KeyboardShortcuts.enable(.popup)
    }
  }

  private func snapshotCurrentPasteboard() -> [[(NSPasteboard.PasteboardType, Data)]] {
    guard let items = pasteboard.pasteboardItems, !items.isEmpty else { return [] }
    return items.compactMap { item in
      let pairs: [(NSPasteboard.PasteboardType, Data)] = item.types.compactMap { type in
        guard isPersistable(type), let data = item.data(forType: type) else { return nil }
        return (type, data)
      }
      return pairs.isEmpty ? nil : pairs
    }
  }

  private func restorePasteboard(from snapshot: [[(NSPasteboard.PasteboardType, Data)]]) {
    pasteboard.clearContents()
    guard !snapshot.isEmpty else { return }

    let restoredItems: [NSPasteboardItem] = snapshot.map { pairs in
      let pbItem = NSPasteboardItem()
      for (type, data) in pairs {
        pbItem.setData(data, forType: type)
      }
      pbItem.setString("", forType: .fromMaccy)
      return pbItem
    }
    pasteboard.writeObjects(restoredItems)
  }

  private func postEmulatedKeys(kind: EmulatedKeyKind, count: Int, syntheticTag: Int64) {
    Accessibility.check()
    let keyCode: CGKeyCode
    switch kind {
    case .tab: keyCode = 48
    case .enter: keyCode = 36
    case .escape: keyCode = 53
    case .leftArrow: keyCode = 123
    case .rightArrow: keyCode = 124
    case .downArrow: keyCode = 125
    case .upArrow: keyCode = 126
    }

    let source = CGEventSource(stateID: .privateState)
    source?.setLocalEventsFilterDuringSuppressionState(
      [.permitLocalMouseEvents, .permitSystemDefinedEvents],
      state: .eventSuppressionStateSuppressionInterval
    )

    for _ in 0..<count {
      let down = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: true)
      let up = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: false)
      down?.flags = []
      up?.flags = []
      down?.setIntegerValueField(.eventSourceUserData, value: syntheticTag)
      up?.setIntegerValueField(.eventSourceUserData, value: syntheticTag)
      down?.post(tap: .cgSessionEventTap)
      up?.post(tap: .cgSessionEventTap)
    }
  }

  private func extractPlainTextData(from item: HistoryItem?) -> Data? {
    if let item {
      // 0. If item is a Microsoft Edge rich titled hyperlink (`org.microsoft.titled-hyperlink`), prefer clean URL
      if item.contents.contains(where: { $0.type == NSPasteboard.PasteboardType.microsoftTitledHyperlink.rawValue }),
         let cleanURL = Self.extractURL(from: item),
         let urlData = cleanURL.absoluteString.data(using: .utf8),
         !urlData.isEmpty {
        return urlData
      }

      // 1. Direct UTF-8 plain text (preserves 100% of even multi-MB text in O(1))
      if let stringContent = item.contents.first(where: { NSPasteboard.PasteboardType($0.type) == .string }),
         let data = stringContent.value,
         !data.isEmpty {
        return data
      }

      // 2. Convert RTF to plain text if plain .string wasn't provided by source app
      if let rtfData = item.rtfData,
         let attr = NSAttributedString(rtf: rtfData, documentAttributes: nil),
         !attr.string.isEmpty,
         let data = attr.string.data(using: .utf8) {
        return data
      }

      // 3. Convert HTML to plain text if plain .string wasn't provided
      if let htmlData = item.htmlData,
         let attr = NSAttributedString(html: htmlData, documentAttributes: nil),
         !attr.string.isEmpty,
         let data = attr.string.data(using: .utf8) {
        return data
      }

      // 4. File URLs -> plain file paths
      if !item.fileURLs.isEmpty {
        let joined = item.fileURLs
          .map { $0.isFileURL ? $0.path : $0.absoluteString }
          .joined(separator: "\n")
        if let data = joined.data(using: .utf8), !data.isEmpty {
          return data
        }
      }

      // 5. OCR text from copied image (if available)
      if !item.title.isEmpty, let data = item.title.data(using: .utf8) {
        return data
      }
    }

    // Fallback directly to system pasteboard plain text
    if let pbData = pasteboard.data(forType: .string), !pbData.isEmpty {
      return pbData
    }
    return nil
  }

  func paste() {
    Accessibility.check()

    let cmdFlag = CGEventFlags(rawValue: UInt64(KeyChord.pasteKeyModifiers.rawValue) | 0x000008)
    var vCode = Sauce.shared.keyCode(for: KeyChord.pasteKey)

    if KeyboardLayout.current.commandSwitchesToQWERTY && cmdFlag.contains(.maskCommand) {
      vCode = KeyChord.pasteKey.QWERTYKeyCode
    }

    let source = CGEventSource(stateID: .combinedSessionState)
    source?.setLocalEventsFilterDuringSuppressionState([.permitLocalMouseEvents, .permitSystemDefinedEvents],
                                                       state: .eventSuppressionStateSuppressionInterval)

    let keyVDown = CGEvent(keyboardEventSource: source, virtualKey: vCode, keyDown: true)
    let keyVUp = CGEvent(keyboardEventSource: source, virtualKey: vCode, keyDown: false)
    keyVDown?.flags = cmdFlag
    keyVUp?.flags = cmdFlag
    keyVDown?.post(tap: .cgSessionEventTap)
    keyVUp?.post(tap: .cgSessionEventTap)
  }

  func clear() {
    guard Defaults[.clearSystemClipboard] else {
      return
    }

    pasteboard.clearContents()
  }

  @objc
  @MainActor
  func checkForChangesInPasteboard() { // swiftlint:disable:this cyclomatic_complexity
    guard !isPerformingPlainTextPaste else {
      changeCount = pasteboard.changeCount
      return
    }

    guard pasteboard.changeCount != changeCount else {
      return
    }

    changeCount = pasteboard.changeCount

    if pasteboard.pasteboardItems?.contains(where: { $0.types.contains(.fromMaccy) }) != true {
      AppState.shared.history.interruptPasteStack()
    }

    if Defaults[.ignoreEvents] {
      if Defaults[.ignoreOnlyNextEvent] {
        Defaults[.ignoreEvents] = false
        Defaults[.ignoreOnlyNextEvent] = false
      }

      return
    }

    if shouldIgnore(Set(pasteboard.types ?? [])) {
      return
    }

    if let sourceAppBundle = sourceApp?.bundleIdentifier, shouldIgnore(sourceAppBundle) {
      return
    }

    let maxLimitMB = Defaults[.maxItemSizeMB]
    let maxBytesLimit = maxLimitMB > 0 ? maxLimitMB * 1_048_576 : Int.max

    var contents = [HistoryItemContent]()
    pasteboard.pasteboardItems?.forEach({ item in
      var types = Set(item.types)
      if types.contains(.string) && isEmptyString(item) && !richText(item) {
        return
      }

      if shouldIgnore(item) {
        return
      }

      let rawItemTypes = Set(item.types)
      if Defaults[.cleanRichURLsFromBrowsers],
         !disabledTypes.contains(.string),
         let cleanURL = Self.extractCleanURLFromTitledHyperlink(
           rawTypes: rawItemTypes,
           stringData: item.data(forType: .string),
           urlData: item.data(forType: .URL),
           htmlData: item.data(forType: .html),
           titledHyperlinkData: item.data(forType: .microsoftTitledHyperlink)
         ),
         let cleanData = cleanURL.shortened(to: maxBytesLimit).data(using: .utf8) {
        contents.append(HistoryItemContent(type: NSPasteboard.PasteboardType.string.rawValue, value: cleanData))
        return
      }

      types = types
        .subtracting(disabledTypes)
        .filter(isPersistable)

      if types.isSuperset(of: [.microsoftLinkSource, .microsoftObjectLink]) {
        types = types.subtracting([.microsoftLinkSource, .microsoftObjectLink, .pdf])
      }

      let hasPlainString = types.contains(.string)

      types.forEach { type in
        guard let data = item.data(forType: type) else { return }

        // Skip redundant multi-megabyte HTML/RTF styling blobs when plain text is already captured
        if hasPlainString && (type == .html || type == .rtf) && data.count > maxRedundantRichTextBytes {
          return
        }

        if data.count > maxBytesLimit {
          // If user configured a max size limit and this is plain text, keep UTF-8 prefix up to maxBytesLimit
          if type == .string,
             let truncated = data.utf8PrefixString(maxBytes: maxBytesLimit)?.data(using: .utf8) {
            contents.append(HistoryItemContent(type: type.rawValue, value: truncated))
          }
          return
        }

        contents.append(HistoryItemContent(type: type.rawValue, value: data))
      }
    })

    guard !contents.isEmpty else {
      return
    }

    let historyItem = HistoryItem(contents: contents)

    if #unavailable(macOS 15.0) {
      try? History.shared.insertIntoStorage(historyItem)
    }

    historyItem.application = sourceApp?.bundleIdentifier
    historyItem.title = historyItem.generateTitle()

    onNewCopyHooks.forEach({ $0(historyItem) })
  }

  private func shouldIgnore(_ types: Set<NSPasteboard.PasteboardType>) -> Bool {
    let ignoredTypes = self.ignoredTypes
      .union(Defaults[.ignoredPasteboardTypes].map({ NSPasteboard.PasteboardType($0) }))

    return types.isDisjoint(with: enabledTypes) ||
      !types.isDisjoint(with: ignoredTypes)
  }

  private func shouldIgnore(_ sourceAppBundle: String) -> Bool {
    if Defaults[.ignoreAllAppsExceptListed] {
      return !Defaults[.ignoredApps].contains(sourceAppBundle)
    } else {
      return Defaults[.ignoredApps].contains(sourceAppBundle)
    }
  }

  private func shouldIgnore(_ item: NSPasteboardItem) -> Bool {
    guard !Defaults[.ignoreRegexp].isEmpty else { return false }
    guard let data = item.data(forType: .string),
          let sample = data.utf8PrefixString(maxBytes: 16_384),
          !sample.isEmpty else {
      return false
    }

    for regexp in Defaults[.ignoreRegexp] {
      do {
        let regex = try NSRegularExpression(pattern: regexp)
        if regex.numberOfMatches(in: sample, range: NSRange(sample.startIndex..., in: sample)) > 0 {
          return true
        }
      } catch {
        return false
      }
    }
    return false
  }

  private func isEmptyString(_ item: NSPasteboardItem) -> Bool {
    guard let data = item.data(forType: .string) else {
      return true
    }
    return data.isEffectivelyEmptyUTF8
  }

  private func richText(_ item: NSPasteboardItem) -> Bool {
    if let rtf = item.data(forType: .rtf), !rtf.isEmpty {
      if rtf.count > 262_144 {
        return true
      }
      if let attributedString = NSAttributedString(rtf: rtf, documentAttributes: nil) {
        return !attributedString.string.isEmpty
      }
    }

    if let html = item.data(forType: .html), !html.isEmpty {
      if html.count > 65_536 {
        return true
      }
      if let attributedString = NSAttributedString(html: html, documentAttributes: nil) {
        return !attributedString.string.isEmpty
      }
    }

    return false
  }

  private func sync() {
    guard let app = sourceApp,
          app.bundleURL?.lastPathComponent == "Chrome Remote Desktop.app" ||
            app.localizedName?.contains("NetBeans") == true else {
      return
    }

    NSApp.activate(ignoringOtherApps: true)
    NSApp.hide(self)
  }

  private func clearFormatting(_ contents: [HistoryItemContent]) -> [HistoryItemContent] {
    var newContents: [HistoryItemContent] = contents
    let stringContents = contents.filter { NSPasteboard.PasteboardType($0.type) == .string }

    if !stringContents.isEmpty {
      newContents = stringContents

      let fileURLContents = contents.filter { NSPasteboard.PasteboardType($0.type) == .fileURL }
      if !fileURLContents.isEmpty {
        newContents += fileURLContents
      }
      return newContents
    }

    if let rtfContent = contents.first(where: { NSPasteboard.PasteboardType($0.type) == .rtf }),
       let rtfData = rtfContent.value,
       let attr = NSAttributedString(rtf: rtfData, documentAttributes: nil),
       let utf8Data = attr.string.data(using: .utf8) {
      return [HistoryItemContent(type: NSPasteboard.PasteboardType.string.rawValue, value: utf8Data)]
    }

    if let htmlContent = contents.first(where: { NSPasteboard.PasteboardType($0.type) == .html }),
       let htmlData = htmlContent.value,
       let attr = NSAttributedString(html: htmlData, documentAttributes: nil),
       let utf8Data = attr.string.data(using: .utf8) {
      return [HistoryItemContent(type: NSPasteboard.PasteboardType.string.rawValue, value: utf8Data)]
    }

    return newContents
  }

  /// Extracts a clean HTTP(S) URL when Microsoft Edge (`org.microsoft.titled-hyperlink`) or a browser
  /// copies an address-bar Rich Link (`<a href="...">Page Title</a>`), leaving normal prose copies untouched.
  nonisolated static func extractCleanURLFromTitledHyperlink(
    rawTypes: Set<NSPasteboard.PasteboardType>,
    stringData: Data?,
    urlData: Data?,
    htmlData: Data?,
    titledHyperlinkData: Data?
  ) -> String? {
    let hasEdgeTitledHyperlink = rawTypes.contains(.microsoftTitledHyperlink)
    let singleAnchorHref = htmlData.flatMap { extractSingleAnchorHref(from: $0) }
    let isBrowserSingleAnchorURL = rawTypes.contains(.URL) && singleAnchorHref != nil

    guard hasEdgeTitledHyperlink || isBrowserSingleAnchorURL else {
      return nil
    }

    if let strData = stringData,
       let plain = strData.utf8PrefixString(maxBytes: 8_192)?.trimmingCharacters(in: .whitespacesAndNewlines),
       isValidStandaloneWebURL(plain) {
      return plain
    }

    if let urlData,
       let rawURL = extractWebURLString(fromURLData: urlData) {
      return rawURL
    }

    if let edgeData = titledHyperlinkData,
       let edgeHref = extractSingleAnchorHref(from: edgeData) ?? extractFirstHref(from: edgeData),
       isValidStandaloneWebURL(edgeHref) {
      return edgeHref
    }

    if let singleAnchorHref, isValidStandaloneWebURL(singleAnchorHref) {
      return singleAnchorHref
    }

    if hasEdgeTitledHyperlink,
       let htmlData,
       let firstHref = extractFirstHref(from: htmlData),
       isValidStandaloneWebURL(firstHref) {
      return firstHref
    }

    return nil
  }

  nonisolated static func extractURL(from item: HistoryItem) -> URL? {
    if let stringData = item.contents.first(where: { NSPasteboard.PasteboardType($0.type) == .string })?.value,
       let plain = stringData.utf8PrefixString(maxBytes: 8_192)?.trimmingCharacters(in: .whitespacesAndNewlines),
       isValidStandaloneWebURL(plain),
       let url = URL(string: plain) {
      return url
    }

    if let urlData = item.contents.first(where: { NSPasteboard.PasteboardType($0.type) == .URL })?.value,
       let urlStr = extractWebURLString(fromURLData: urlData),
       let url = URL(string: urlStr) {
      return url
    }

    if let edgeData = item.contents.first(where: { $0.type == NSPasteboard.PasteboardType.microsoftTitledHyperlink.rawValue })?.value,
       let href = extractFirstHref(from: edgeData),
       isValidStandaloneWebURL(href),
       let url = URL(string: href) {
      return url
    }

    if let htmlData = item.htmlData,
       let href = extractSingleAnchorHref(from: htmlData),
       isValidStandaloneWebURL(href),
       let url = URL(string: href) {
      return url
    }

    return nil
  }

  /// Strips common marketing/tracking query parameters (`utm_*`, `fbclid`, `gclid`, `msclkid`, `igshid`, etc.).
  nonisolated static func stripTrackingParameters(from url: URL) -> URL {
    guard var components = URLComponents(url: url, resolvingAgainstBaseURL: false),
          let items = components.queryItems,
          !items.isEmpty else {
      return url
    }

    let exactTrackingKeys: Set<String> = [
      "fbclid", "gclid", "dclid", "msclkid", "igshid", "mc_cid", "mc_eid", "yclid", "_hsenc", "_hsmi"
    ]
    let filtered = items.filter { item in
      let key = item.name.lowercased()
      if key.hasPrefix("utm_") { return false }
      if exactTrackingKeys.contains(key) { return false }
      return true
    }

    guard filtered.count != items.count else { return url }
    components.queryItems = filtered.isEmpty ? nil : filtered
    return components.url ?? url
  }

  private nonisolated static func isValidStandaloneWebURL(_ string: String) -> Bool {
    guard !string.isEmpty,
          string.rangeOfCharacter(from: .whitespacesAndNewlines) == nil,
          let url = URL(string: string),
          let scheme = url.scheme?.lowercased(),
          (scheme == "http" || scheme == "https"),
          url.host != nil else {
      return false
    }
    return true
  }

  private nonisolated static func extractWebURLString(fromURLData data: Data) -> String? {
    if let str = data.utf8PrefixString(maxBytes: 8_192)?.trimmingCharacters(in: .whitespacesAndNewlines),
       isValidStandaloneWebURL(str) {
      return str
    }
    if let plist = try? PropertyListSerialization.propertyList(from: data, options: [], format: nil) as? [Any],
       let firstStr = plist.first as? String,
       isValidStandaloneWebURL(firstStr) {
      return firstStr
    }
    return nil
  }

  private nonisolated static func extractSingleAnchorHref(from data: Data) -> String? {
    guard data.count <= 8_192,
          let html = data.utf8PrefixString(maxBytes: 8_192)?.trimmingCharacters(in: .whitespacesAndNewlines),
          !html.isEmpty else {
      return nil
    }
    // Strip optional <meta ...> or <!--StartFragment--> wrappers emitted by Chromium/Edge
    let stripped = html
      .replacingOccurrences(of: "(?is)<!--.*?-->", with: "", options: .regularExpression)
      .replacingOccurrences(of: "(?is)<meta[^>]*>", with: "", options: .regularExpression)
      .trimmingCharacters(in: .whitespacesAndNewlines)

    let pattern = "^(?is)<a\\b[^>]*\\bhref\\s*=\\s*[\"']([^\"']+)[\"'][^>]*>.*?</a>$"
    guard let regex = try? NSRegularExpression(pattern: pattern),
          let match = regex.firstMatch(in: stripped, range: NSRange(stripped.startIndex..., in: stripped)),
          match.numberOfRanges > 1,
          let hrefRange = Range(match.range(at: 1), in: stripped) else {
      return nil
    }
    return unescapeHTMLAttribute(String(stripped[hrefRange]))
  }

  private nonisolated static func extractFirstHref(from data: Data) -> String? {
    guard let text = data.utf8PrefixString(maxBytes: 16_384), !text.isEmpty else { return nil }
    let pattern = "(?is)\\bhref\\s*=\\s*[\"'](https?://[^\"'\\s>]+)[\"']"
    if let regex = try? NSRegularExpression(pattern: pattern),
       let match = regex.firstMatch(in: text, range: NSRange(text.startIndex..., in: text)),
       match.numberOfRanges > 1,
       let hrefRange = Range(match.range(at: 1), in: text) {
      return unescapeHTMLAttribute(String(text[hrefRange]))
    }
    let urlPattern = "https?://[^\\s\"'<>\\0]+"
    if let regex = try? NSRegularExpression(pattern: urlPattern),
       let match = regex.firstMatch(in: text, range: NSRange(text.startIndex..., in: text)),
       let urlRange = Range(match.range(at: 0), in: text) {
      return unescapeHTMLAttribute(String(text[urlRange]))
    }
    return nil
  }

  private nonisolated static func unescapeHTMLAttribute(_ value: String) -> String {
    value
      .replacingOccurrences(of: "&amp;", with: "&")
      .replacingOccurrences(of: "&#38;", with: "&")
      .replacingOccurrences(of: "&quot;", with: "\"")
      .replacingOccurrences(of: "&#39;", with: "'")
  }
